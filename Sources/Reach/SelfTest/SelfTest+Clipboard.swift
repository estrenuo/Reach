import AppKit
import ReachKit
import SwiftData

extension SelfTest {
    /// S-025: copies are kept per kind for the chosen time, never from
    /// password managers or when marked private. A private pasteboard and
    /// the test store, so the real clipboard is never read.
    static func checkClipboard(model: AppModel) async {
        check("test runs never watch the real clipboard", model.clipboard == nil)
        let settings = ClipboardSettings.shared
        let pasteboard = NSPasteboard.withUniqueName()
        let context = model.container.mainContext
        let history = ClipboardHistory(pasteboard: pasteboard, context: context, settings: settings)
        var app: (name: String, bundleID: String)? = ("TextEdit", "com.apple.TextEdit")
        var now = Date.now
        history.frontApp = { app }
        history.now = { now }
        defer {
            history.stop()
            history.items.forEach(context.delete)
            try? context.save()
            settings.reset()
            pasteboard.releaseGlobally()
        }
        func copy(_ text: String, extra: [NSPasteboard.PasteboardType] = []) {
            pasteboard.declareTypes([.string] + extra, owner: nil)
            pasteboard.setString(text, forType: .string)
        }

        copy("before it was on")
        check("with every kind off, nothing is kept", !history.poll() && history.items.isEmpty)
        settings.keep[.text] = true
        check("the settings are the test run's own", Store.settings !== UserDefaults.standard
              && Store.settings.bool(forKey: "clipboard.keep.text"))
        copy("Hallo Reach")
        history.poll()
        let first = history.items.first
        check("copied text is kept, with the app it came from",
              history.items.count == 1 && first?.text == "Hallo Reach" && first?.clipKind == .text && first?.sourceApp == "TextEdit")
        check("an unchanged clipboard keeps nothing new", !history.poll() && history.items.count == 1)
        now += 60
        copy("Second")
        history.poll()
        now += 60
        copy("Hallo Reach")
        history.poll()
        check("copying the same text again moves it to the top",
              history.items.map(\.text) == ["Hallo Reach", "Second"], history.items.map(\.text).joined(separator: ", "))

        copy("secret-password", extra: [NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")])
        check("a copy marked private is never kept", !history.poll() && !history.items.contains { $0.text == "secret-password" })
        copy("auto", extra: [NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")])
        check("a machine-made copy is never kept", !history.poll())
        app = ("Keychain Access", "com.apple.keychainaccess")
        copy("from keychain")
        check("a copy from Keychain Access is never kept", !history.poll())
        app = ("1Password", "com.1password.1password")
        copy("from 1password")
        check("a copy from 1Password is never kept", !history.poll())
        app = ("Preview", "com.apple.Preview")

        let image = NSImage(size: NSSize(width: 8, height: 8), flipped: false) { rect in
            NSColor.systemBlue.setFill()
            rect.fill()
            return true
        }
        func copyImage() {
            pasteboard.clearContents()
            pasteboard.writeObjects([image])
        }
        copyImage()
        check("an image is not kept while images are off", !history.poll())
        settings.keep[.image] = true
        now += 60
        copyImage()
        history.poll()
        check("with images on, the image is kept", history.items.first?.clipKind == .image && history.items.first?.imageData != nil)
        settings.keep[.files] = true
        now += 60
        pasteboard.clearContents()
        let files = [URL(fileURLWithPath: "/tmp/reach-a.txt"), URL(fileURLWithPath: "/tmp/reach-b.txt")]
        pasteboard.writeObjects(files.map { $0 as NSURL })
        history.poll()
        check("a file list is kept as its paths", history.items.first?.clipKind == .files
              && history.items.first?.text == "/tmp/reach-a.txt\n/tmp/reach-b.txt", history.items.first?.text ?? "none")

        now += 2 * 24 * 60 * 60
        let purged = history.purge()
        check("after 2 days the image and the file list are gone, text stays (24 hours and 7 days)",
              purged == 2 && history.items.allSatisfy { $0.clipKind == .text } && history.items.count == 2, "purged \(purged)")
        settings.retention[.text] = .day
        check("a shorter retention purges at once", history.purge() == 2 && history.items.isEmpty)
        settings.retention[.text] = .month
        copy("kept a month")
        history.poll()
        now += 8 * 24 * 60 * 60
        check("a month's text survives 8 days", history.purge() == 0 && history.items.count == 1)

        history.start()
        check("watching purges at start and every hour", history.isRunning && history.purgesHourly)
        history.stop()
    }
}
