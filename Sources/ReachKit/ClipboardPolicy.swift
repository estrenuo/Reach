import Foundation

/// What the clipboard history keeps and for how long (S-025). Plain values
/// only, so the rules are unit-tested without a pasteboard.
public enum ClipboardPolicy {
    public enum Kind: String, CaseIterable, Codable, Sendable {
        case text, image, files

        public var title: String {
            switch self {
            case .text: "Plain Text"
            case .image: "Images"
            case .files: "File Lists"
            }
        }
    }

    public enum Retention: Int, CaseIterable, Codable, Sendable {
        case day = 1, week = 7, month = 30, quarter = 90

        public var title: String {
            switch self {
            case .day: "24 Hours"
            case .week: "7 Days"
            case .month: "1 Month"
            case .quarter: "3 Months"
            }
        }

        public var seconds: TimeInterval { TimeInterval(rawValue) * 24 * 60 * 60 }
    }

    /// The standard retention per kind: text a week, the rest a day, as in Alfred.
    public static func standardRetention(_ kind: Kind) -> Retention { kind == .text ? .week : .day }

    /// How often expired clips are purged while the app runs, besides at launch.
    public static let purgeInterval: TimeInterval = 60 * 60

    /// Pasteboard types that mark a copy as private or machine-made
    /// (nspasteboard.org): password managers set these, so it is never kept.
    public static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "com.typeit4me.clipping",
    ]

    /// Apps whose copies are never kept, before Settings adds any (S-027 adds the list).
    public static let standardIgnoredApps: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
        "in.sinew.Enpass-Desktop",
        "com.dashlane.dashlanephonefinal",
        "org.keepassxc.keepassxc",
    ]

    static let fileTypes: Set<String> = ["public.file-url", "NSFilenamesPboardType"]
    static let textTypes: Set<String> = ["public.utf8-plain-text", "NSStringPboardType", "public.plain-text"]
    static let imageTypes: Set<String> = ["public.png", "public.tiff", "public.jpeg", "NSTIFFPboardType"]

    /// The kind a copy counts as: files first (Finder also puts their names
    /// as text), then text (Word puts a picture of the text too), then images.
    public static func kind(of types: [String]) -> Kind? {
        let set = Set(types)
        if !set.isDisjoint(with: fileTypes) { return .files }
        if !set.isDisjoint(with: textTypes) { return .text }
        if !set.isDisjoint(with: imageTypes) { return .image }
        return nil
    }

    /// What to keep of a copy, or nil to keep nothing: a private or
    /// machine-made copy, one from an ignored app, or a kind that is off.
    public static func keep(types: [String], from app: String?, ignoredApps: Set<String>, on: Set<Kind>) -> Kind? {
        guard Set(types).isDisjoint(with: ignoredTypes) else { return nil }
        if let app, ignoredApps.contains(app) { return nil }
        guard let kind = kind(of: types), on.contains(kind) else { return nil }
        return kind
    }

    /// True when a clip of `kind` copied at `date` is past its retention at `now`.
    public static func isExpired(_ date: Date, kind: Kind, retention: (Kind) -> Retention, now: Date) -> Bool {
        now.timeIntervalSince(date) > retention(kind).seconds
    }
}
