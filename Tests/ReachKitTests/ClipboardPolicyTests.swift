import Foundation
import Testing
@testable import ReachKit

struct ClipboardPolicyTests {
    let all = Set(ClipboardPolicy.Kind.allCases)
    let ignored = ClipboardPolicy.standardIgnoredApps

    @Test func kinds() {
        #expect(ClipboardPolicy.kind(of: ["public.utf8-plain-text"]) == .text)
        #expect(ClipboardPolicy.kind(of: ["public.png"]) == .image)
        // Finder copies a file with its name as text: it is a file list.
        #expect(ClipboardPolicy.kind(of: ["public.file-url", "public.utf8-plain-text"]) == .files)
        // Word copies text with a picture of it: it is text.
        #expect(ClipboardPolicy.kind(of: ["public.utf8-plain-text", "public.tiff"]) == .text)
        #expect(ClipboardPolicy.kind(of: ["com.example.private"]) == nil)
    }

    @Test func concealedAndGeneratedCopiesAreNeverKept() {
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            #expect(ClipboardPolicy.keep(types: ["public.utf8-plain-text", type], from: nil, ignoredApps: [], on: all) == nil)
        }
    }

    @Test func ignoredAppsAreNeverKept() {
        #expect(ClipboardPolicy.keep(types: ["public.utf8-plain-text"], from: "com.apple.keychainaccess", ignoredApps: ignored, on: all) == nil)
        #expect(ClipboardPolicy.keep(types: ["public.utf8-plain-text"], from: "com.1password.1password", ignoredApps: ignored, on: all) == nil)
        #expect(ClipboardPolicy.keep(types: ["public.utf8-plain-text"], from: "com.apple.TextEdit", ignoredApps: ignored, on: all) == .text)
    }

    @Test func onlyKindsThatAreOn() {
        #expect(ClipboardPolicy.keep(types: ["public.png"], from: nil, ignoredApps: [], on: [.text]) == nil)
        #expect(ClipboardPolicy.keep(types: ["public.png"], from: nil, ignoredApps: [], on: [.image]) == .image)
        #expect(ClipboardPolicy.keep(types: ["public.utf8-plain-text"], from: nil, ignoredApps: [], on: []) == nil)
    }

    @Test func retentionPerKind() {
        let now = Date(timeIntervalSince1970: 1_000_000_000)
        let retention: (ClipboardPolicy.Kind) -> ClipboardPolicy.Retention = ClipboardPolicy.standardRetention
        let twoDays = now.addingTimeInterval(-2 * 24 * 60 * 60)
        #expect(!ClipboardPolicy.isExpired(twoDays, kind: .text, retention: retention, now: now))
        #expect(ClipboardPolicy.isExpired(twoDays, kind: .image, retention: retention, now: now))
        #expect(ClipboardPolicy.isExpired(now.addingTimeInterval(-8 * 24 * 60 * 60), kind: .text, retention: retention, now: now))
        #expect(!ClipboardPolicy.isExpired(now.addingTimeInterval(-60), kind: .files, retention: retention, now: now))
    }

    @Test func retentionTitles() {
        #expect(ClipboardPolicy.Retention.allCases.map(\.title) == ["24 Hours", "7 Days", "1 Month", "3 Months"])
        #expect(ClipboardPolicy.purgeInterval == 3600)
    }
}
